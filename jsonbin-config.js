//   فاکتور روی دکمه "⬆️ ارسال به jsonbin.io" بزنید، یک Bin جدید به‌صورت خودکار
//   ساخته می‌شود و شناسه‌اش در یک پیام روی صفحه نمایش داده می‌شود. آن شناسه را
//   کپی کرده و همین‌جا در binId بچسبانید تا از این پس همیشه همان Bin استفاده شود.
//
// بعد از تنظیم درست این دو مقدار، فاکتور با باز شدن هر بار به‌صورت خودکار آخرین
// اطلاعات را از jsonbin.io می‌خواند و با هر تغییری (تنظیمات، سوابق فاکتورها،
// تسویه‌ها) آن‌ها را خودکار در همان‌جا ذخیره می‌کند — بدون نیاز به هیچ تأییدیه
// یا انتخاب فایلی در مرورگر.
//
