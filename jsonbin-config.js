//   می‌دهد اطلاعات این Bin را بخواند یا تغییر دهد. این فایل را در جای عمومی
//   (مثل یک وب‌سایت عمومی، ایمیل، یا مخزن گیت‌هاب عمومی) قرار ندهید.
