// اگر این بخش را تکمیل کنید، هر تصویری که آپلود می‌کنید ابتدا روی ImageKit.io
// بارگذاری می‌شود و فقط "لینک" کوچک آن تصویر (نه خود فایل تصویر) داخل jsonbin
// ذخیره می‌شود. اگر این بخش را خالی بگذارید، تصاویر مستقیم و به‌صورت کامل
// داخل jsonbin ذخیره می‌شوند که ممکن است به سقف حجم رایگان آن برسد.
//
// راهنمای دقیق مرحله‌به‌مرحله بعد از ثبت‌نام در ImageKit.io:
//
//   ۱. به آدرس https://imagekit.io بروید و یک حساب رایگان بسازید (ایمیل یا
//      حساب گوگل/گیت‌هاب کافی است). در مرحله ساخت حساب، از شما یک
//      "ID" برای فضای کاری می‌خواهد (مثلاً nام‌فروشگاه‌شما) — همانی که
//      انتخاب می‌کنید در آدرس تصاویر شما ظاهر می‌شود، هرچه دوست دارید بگذارید.
//
//   ۲. بعد از ورود به داشبورد، از منوی سمت چپ روی گزینه‌ی
//      "Developer options" (یا آیکون </> در بالا) کلیک کنید تا وارد
//      بخش "API Keys" شوید.
//
//   ۳. در همان صفحه دو مقدار زیر را خواهید دید — هر دو را کپی کنید:
//        - "Public key"  → مقدار publicKey پایین همین فایل
//        - "Private key" → مقدار privateKey پایین همین فایل
//        (روی دکمه چشم/Show کنار Private key بزنید تا نمایش داده شود)
//
//   ۴. کمی بالاتر از همان صفحه، مقدار "URL-endpoint" را هم می‌بینید —
//      چیزی شبیه https://ik.imagekit.io/xxxxxxxxx — آن را هم کپی کرده
//      و در urlEndpoint پایین جایگزین کنید.
//
//   ۵. (پیشنهاد امنیتی، اختیاری ولی خیلی بهتر) به‌جای استفاده از همین
//      کلید اصلی، از منوی API Keys روی "Create new key" بزنید، نوع را
//      روی "Restricted" بگذارید، و فقط دسترسی «Upload» را فعال کنید
//      (نه Read/Delete/Manage). این‌طوری اگر روزی این فایل به دست کسی
//      افتاد، او فقط می‌تواند تصویر آپلود کند، نه اینکه فایل‌های شما را
//      ببیند یا پاک کند.
//
